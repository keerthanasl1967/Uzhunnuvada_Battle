def get_vada_comment(iq):
    if iq >= 90:
        return "🏆 This vada has a PhD in deliciousness!"

    elif iq >= 75:
        return "😎 A respectable vada. The family is proud!"

    elif iq >= 50:
        return "🤨 Not bad... but something suspicious happened in the frying pan."

    else:
        return "💀 Please apologize to the urad dal."